let lang = 'en';
export const setLang = (l) => { lang = STRINGS[l] ? l : 'en'; document.documentElement.lang = lang; };
export const getLang = () => lang;

/* t('inDays', {n: 3}) → "3 days" */
export function t(key, vars) {
  let s = STRINGS[lang][key] ?? STRINGS.en[key] ?? key;
  if (vars) for (const k in vars) s = s.replaceAll(`{${k}}`, vars[k]);
  return s;
}

/* Bilingual data objects ({en, el}) → text in the current language. */
export const tr = (obj) => (obj ? obj[lang] ?? obj.en : '');
export const catName = (id) => tr(CATEGORIES[id] || CATEGORIES.other);
export const groupName = (id) => tr(PICK_GROUPS.find((g) => g.id === id));
